/// Controlled public-conversion responses for error-path tests only.
/// Not PDFKit calibration evidence and never used by the signed diagnostic.
@MainActor private final class StrictBoundaryPDFView: PDFView {
    var outsideInverse = false
    var inverseBias = 0.0
    var pointTranslationError = 0.0
    override var isFlipped: Bool { false }
    override func convert(_ rect: CGRect, from page: PDFPage) -> CGRect {
        rect.offsetBy(dx: 300, dy: 400)
    }
    override func convert(_ point: CGPoint, from page: PDFPage) -> CGPoint {
        CGPoint(x: point.x + 300 + pointTranslationError, y: point.y + 400)
    }
    override func convert(_ point: CGPoint, to page: PDFPage) -> CGPoint {
        let x = Double(point.x - 300 - pointTranslationError)
        return CGPoint(x: (outsideInverse && x == 200 ? x.nextUp : x) + inverseBias, y: point.y - 400)
    }
}

