    func testExplicitPrecisionBoundaryAndFiniteAffineMapping() throws {
        // Exact binary arithmetic witnesses; this is not an owning product precision profile.
        let precision = try PDFGeometryPrecision(maximumErrorPDFPoints: 0.5)
        try precision.validate(expected: PDFPoint(x: 0, y: 0), actual: PDFPoint(x: 0.5, y: -0.5))
        assertError(.roundtripExceeded) {
            try precision.validate(expected: PDFPoint(x: 0, y: 0),
                                   actual: PDFPoint(x: Double(0.5).nextUp, y: 0))
        }
        let exact = try PDFGeometryPrecision(maximumErrorPDFPoints: 0)
        let affine = try PDFGeometryAffine(a: 0, b: 2, c: -2, d: 0, tx: 400, ty: -20)
        let point = PDFPoint(x: 35, y: 80)
        XCTAssertEqual(try affine.applying(point), PDFPoint(x: 240, y: 50))
        try exact.validate(expected: point, actual: affine.inverse(PDFPoint(x: 240, y: 50)))
        assertError(.malformedGeometry) {
            try PDFGeometryAffine(a: 1, b: 2, c: 2, d: 4, tx: 0, ty: 0)
        }
        assertError(.malformedGeometry) {
            try affine.applying(PDFPoint(x: .nan, y: 0))
        }
        assertError(.malformedGeometry) {
            try PDFGeometryAffine(a: .infinity, b: 0, c: 0, d: 1, tx: 0, ty: 0)
        }
    }

    @MainActor
    func testPDFKitSyntheticPageMappingAllRotationsAndDifferentPage() throws {
        // Source-only fixture: no user file, PDFium/helper, render, window or native-frame trial.
        let bytes = NSMutableData()
        let consumer = try XCTUnwrap(CGDataConsumer(data: bytes as CFMutableData))
        var mediaBox = CGRect(x: 0, y: 0, width: 300, height: 400)
        let context = try XCTUnwrap(CGContext(consumer: consumer, mediaBox: &mediaBox, nil))
        context.beginPDFPage(nil)
        context.endPDFPage()
        context.closePDF()
        let document = try XCTUnwrap(PDFDocument(data: bytes as Data))
        let pdfPage = try XCTUnwrap(document.page(at: 0))
        pdfPage.setBounds(CGRect(x: 10, y: 20, width: 100, height: 200), for: .cropBox)
        let view = PDFView(frame: CGRect(x: 0, y: 0, width: 600, height: 800))
        view.displayMode = .singlePage
        view.autoScales = false
        view.document = document
        let exact = try PDFGeometryPrecision(maximumErrorPDFPoints: 0)
        for rotation in [0, 90, 180, 270] {
            pdfPage.rotation = rotation
            for scale in [1.0, 2.0] {
                view.scaleFactor = scale
                view.layoutDocumentView()
                let geometry = try PDFKitGeometryAdapter.pageGeometry(page: pdfPage, in: view, pageIndex: 0)
                XCTAssertEqual(geometry, try page(rotation: rotation))
                let canonical = PDFPoint(x: 35, y: 80)
                let landmarks = [geometry.cropOrigin,
                                 PDFPoint(x: 110, y: 20), PDFPoint(x: 10, y: 220),
                                 PDFPoint(x: 110, y: 220), canonical]
                let publicDisplay = landmarks.map {
                    view.convert(CGPoint(x: $0.x, y: $0.y), from: pdfPage)
                }
                let publicBack = publicDisplay.map { view.convert($0, to: pdfPage) }
                // Fixture-only IEEE-754 forward-error budget, not a product profile.
                // u is binary64 unit roundoff. gamma(64) = 64u/(1-64u) covers
                // a conservative 64 scalar operations along the affine path:
                // basis differences/divisions, intercept construction, application,
                // determinant/inversion and forward/inverse affine evaluation.
                // Sum absolute page/display terms (display divided by this fixture's
                // uniform scale) rather than net coordinates: translations can cancel.
                // PDFKit's implementation is opaque; independently ASSERT its public
                // roundtrip fits this model. Never derive the budget from residuals.
                let u = Double.ulpOfOne / 2
                let gamma64 = (64 * u / (1 - 64 * u)).nextUp
                let magnitude = landmarks.reduce(0.0) { $0 + abs($1.x) + abs($1.y) }
                    + publicDisplay.reduce(0.0) {
                        $0 + (abs(Double($1.x)) + abs(Double($1.y))) / scale
                    } + geometry.width + geometry.height
                let bound = (gamma64 * magnitude).nextUp
                XCTAssertTrue(bound.isFinite && bound > 0)
                let configured = try PDFGeometryPrecision(maximumErrorPDFPoints: bound)
                for (landmark, back) in zip(landmarks, publicBack) {
                    let actual = PDFPoint(x: Double(back.x), y: Double(back.y))
                    try configured.validate(expected: landmark, actual: actual)
                    if actual != landmark {
                        // Zero really means zero: independent public PDFKit rounding
                        // must fail, not get silently accepted by the adapter.
                        assertError(.roundtripExceeded) {
                            try exact.validate(expected: landmark, actual: actual)
                        }
                        assertError(.roundtripExceeded) {
                            try PDFKitGeometryAdapter.displayPoint(
                                landmark, page: pdfPage, in: view,
                                geometry: geometry, precision: exact)
                        }
                    }
                }
                let display = try PDFKitGeometryAdapter.displayPoint(canonical, page: pdfPage, in: view,
                                                                    geometry: geometry, precision: configured)
                let direct = view.convert(CGPoint(x: 35, y: 80), from: pdfPage)
                XCTAssertEqual(display.x, Double(direct.x), accuracy: bound * scale)
                XCTAssertEqual(display.y, Double(direct.y), accuracy: bound * scale)
                let restored = try PDFKitGeometryAdapter.canonicalPoint(
                    display, page: pdfPage, in: view, geometry: geometry, precision: configured)
                try configured.validate(expected: canonical, actual: restored)
                assertError(.outsidePage) {
                    try PDFKitGeometryAdapter.displayPoint(PDFPoint(x: 9, y: 80), page: pdfPage, in: view,
                                                            geometry: geometry, precision: exact)
                }
            }
        }
        assertError(.missingPage) {
            try PDFKitGeometryAdapter.pageGeometry(page: pdfPage, in: PDFView(), pageIndex: 0)
        }
        assertError(.missingPage) {
            try PDFKitGeometryAdapter.pageGeometry(page: pdfPage, in: view, pageIndex: 1)
        }
        let otherDocument = try XCTUnwrap(PDFDocument(data: bytes as Data))
        let otherPage = try XCTUnwrap(otherDocument.page(at: 0))
        assertError(.differentPage) {
            try PDFKitGeometryAdapter.pageGeometry(page: otherPage, in: view, pageIndex: 0)
        }
    }
