import XCTest
import PDFKit
@testable import PaperLensProduct

final class PDFGeometryTests: XCTestCase {
    private let paperID = UUID(uuidString: "00000000-0000-4000-8000-000000000001")!
    private let revision = "00000000-0000-4000-8000-000000000002"

    private func page(rotation: Int = 0, pageIndex: Int = 0) throws -> PDFPageGeometry {
        try PDFPageGeometry(pageIndex: pageIndex, cropOrigin: PDFPoint(x: 10, y: 20),
                            width: 100, height: 200, rotation: rotation)
    }

    private func identity(paper: UUID? = nil, hash: String? = nil, revision: String? = nil,
                          page: Int = 0, sentence: Int = 7) throws -> PDFSentenceIdentity {
        try PDFSentenceIdentity(paperID: paper ?? paperID,
                                pdfSHA256: hash ?? String(repeating: "a", count: 64),
                                extractionRevision: revision ?? self.revision,
                                pageIndex: page, sentenceID: sentence)
    }

    private func quad(on page: PDFPageGeometry) throws -> PDFQuad {
        try PDFQuad(topLeft: PDFPoint(x: 15, y: 200), topRight: PDFPoint(x: 90, y: 200),
                    bottomRight: PDFPoint(x: 90, y: 180), bottomLeft: PDFPoint(x: 15, y: 180),
                    page: page)
    }

    private func assertError<T>(_ expected: PDFGeometryError,
                                file: StaticString = #filePath, line: UInt = #line,
                                _ body: () throws -> T) {
        XCTAssertThrowsError(try body(), file: file, line: line) {
            XCTAssertEqual($0 as? PDFGeometryError, expected, file: file, line: line)
        }
    }

    func testIndependentClockwiseRotationLandmarksAndInverse() throws {
        // Independently specified display landmarks, not results generated by the inverse.
        let canonical = PDFPoint(x: 35, y: 80) // crop-local (25,60)
        let expected = [PDFPoint(x: 25, y: 140), PDFPoint(x: 60, y: 25),
                        PDFPoint(x: 75, y: 60), PDFPoint(x: 140, y: 75)]
        let corners = [[PDFPoint(x: 0, y: 200), PDFPoint(x: 100, y: 0)],
                       [PDFPoint(x: 0, y: 0), PDFPoint(x: 200, y: 100)],
                       [PDFPoint(x: 100, y: 0), PDFPoint(x: 0, y: 200)],
                       [PDFPoint(x: 200, y: 100), PDFPoint(x: 0, y: 0)]]
        for (index, rotation) in [0, 90, 180, 270].enumerated() {
            let geometry = try page(rotation: rotation)
            XCTAssertEqual(try geometry.rotatedTopLeft(fromCanonical: canonical), expected[index])
            XCTAssertEqual(try geometry.canonical(fromRotatedTopLeft: expected[index]), canonical)
            XCTAssertEqual(try geometry.rotatedTopLeft(fromCanonical: PDFPoint(x: 10, y: 20)),
                           corners[index][0])
            XCTAssertEqual(try geometry.rotatedTopLeft(fromCanonical: PDFPoint(x: 110, y: 220)),
                           corners[index][1])
        }
    }

    func testCropOffsetAndInclusivePageBoundaries() throws {
        let geometry = try page()
        XCTAssertEqual(try geometry.canonicalFromCropTopLeft(PDFPoint(x: 0, y: 0)),
                       PDFPoint(x: 10, y: 220))
        XCTAssertEqual(try geometry.canonicalFromCropTopLeft(PDFPoint(x: 25, y: 140)),
                       PDFPoint(x: 35, y: 80))
        XCTAssertEqual(try geometry.canonicalFromCropTopLeft(PDFPoint(x: 100, y: 200)),
                       PDFPoint(x: 110, y: 20))
        assertError(.outsidePage) { try geometry.validate(PDFPoint(x: Double(10).nextDown, y: 20)) }
        assertError(.outsidePage) { try geometry.validate(PDFPoint(x: Double(110).nextUp, y: 220)) }
        assertError(.outsidePage) {
            try geometry.canonicalFromCropTopLeft(PDFPoint(x: 101, y: 20))
        }
        assertError(.outsidePage) {
            try geometry.canonicalFromCropTopLeft(PDFPoint(x: -Double.leastNonzeroMagnitude, y: 0))
        }
        for rotation in [0, 90, 180, 270] {
            let rotated = try page(rotation: rotation)
            assertError(.outsidePage) {
                try rotated.canonical(fromRotatedTopLeft: PDFPoint(x: -1, y: 0))
            }
            assertError(.outsidePage) {
                try rotated.canonical(fromRotatedTopLeft: PDFPoint(x: -Double.leastNonzeroMagnitude, y: 0))
            }
        }
    }

    func testNonfiniteDegenerateUnsupportedInputs() throws {
        for invalid in [Double.nan, Double.infinity, -Double.infinity] {
            assertError(.malformedGeometry) { try page().validate(PDFPoint(x: invalid, y: 30)) }
            assertError(.malformedGeometry) {
                try PDFPageGeometry(pageIndex: 0, cropOrigin: PDFPoint(x: 10, y: 20),
                                    width: invalid, height: 200, rotation: 0)
            }
            assertError(.invalidPrecision) { try PDFGeometryPrecision(maximumErrorPDFPoints: invalid) }
        }
        for width in [0.0, -1.0] {
            assertError(.malformedGeometry) {
                try PDFPageGeometry(pageIndex: 0, cropOrigin: PDFPoint(x: 10, y: 20),
                                    width: width, height: 200, rotation: 0)
            }
        }
        assertError(.unsupportedRotation) { try page(rotation: 45) }
        assertError(.malformedGeometry) {
            try PDFPageGeometry(pageIndex: 0, cropOrigin: PDFPoint(x: 1e300, y: 20),
                                width: 1, height: 200, rotation: 0)
        }
        assertError(.malformedGeometry) { try page(pageIndex: -1) }
        assertError(.malformedGeometry) { try page(pageIndex: 2000) }
        assertError(.invalidPrecision) { try PDFGeometryPrecision(maximumErrorPDFPoints: -1) }
    }

    func testQuadOrderingDegeneracyAndMultilineSemanticExtent() throws {
        let geometry = try page()
        let first = try quad(on: geometry)
        let second = try PDFQuad(topLeft: PDFPoint(x: 15, y: 170), topRight: PDFPoint(x: 70, y: 170),
                                 bottomRight: PDFPoint(x: 70, y: 150), bottomLeft: PDFPoint(x: 15, y: 150),
                                 page: geometry)
        let quote = "First line remains complete,\nincluding its continuation."
        let anchor = try PDFSentenceAnchor(identity: identity(), fullSourceQuote: quote,
                                           page: geometry, quads: [first, second])
        XCTAssertEqual(anchor.fullSourceQuote, quote)
        XCTAssertEqual(anchor.quads, [first, second])
        XCTAssertEqual(first.points, [PDFPoint(x: 15, y: 200), PDFPoint(x: 90, y: 200),
                                      PDFPoint(x: 90, y: 180), PDFPoint(x: 15, y: 180)])
        assertError(.malformedGeometry) {
            try PDFQuad(topLeft: first.topLeft, topRight: first.bottomLeft,
                        bottomRight: first.bottomRight, bottomLeft: first.topRight, page: geometry)
        }
        assertError(.malformedGeometry) {
            try PDFQuad(topLeft: first.topLeft, topRight: first.topLeft,
                        bottomRight: first.bottomRight, bottomLeft: first.bottomLeft, page: geometry)
        }
        assertError(.outsidePage) {
            try PDFQuad(topLeft: PDFPoint(x: 0, y: 200), topRight: first.topRight,
                        bottomRight: first.bottomRight, bottomLeft: first.bottomLeft, page: geometry)
        }
        assertError(.missingGeometry) {
            try PDFSentenceAnchor(identity: identity(), fullSourceQuote: quote, page: geometry, quads: [])
        }
        assertError(.differentPage) {
            try PDFSentenceAnchor(identity: identity(page: 1), fullSourceQuote: quote,
                                  page: geometry, quads: [first])
        }
    }

    func testExactTupleMembershipAndEachIndependentMismatch() throws {
        let geometry = try page()
        let id = try identity()
        let anchor = try PDFSentenceAnchor(identity: id, fullSourceQuote: "The whole sentence.",
                                           page: geometry, quads: [quad(on: geometry)])
        try anchor.validateResolution(expected: id, publishedMembership: [id])
        let mismatches = [try identity(paper: UUID()), try identity(hash: String(repeating: "b", count: 64)),
                          try identity(page: 1), try identity(sentence: 8)]
        for mismatch in mismatches {
            assertError(.identityMismatch) {
                try anchor.validateResolution(expected: mismatch, publishedMembership: [id])
            }
        }
        assertError(.staleRevision) {
            try anchor.validateResolution(
                expected: identity(revision: "00000000-0000-4000-8000-000000000003"),
                publishedMembership: [id])
        }
        assertError(.unknownSentence) {
            try anchor.validateResolution(expected: id, publishedMembership: [])
        }
        _ = try identity(page: 1999, sentence: 199999)
        for pair in [(-1, 0), (2000, 0), (0, -1), (0, 200000)] {
            assertError(.invalidIdentity) { try identity(page: pair.0, sentence: pair.1) }
        }
        assertError(.invalidIdentity) { try identity(hash: String(repeating: "A", count: 64)) }
        assertError(.invalidIdentity) { try identity(revision: "unknown") }
        assertError(.invalidIdentity) { try identity(revision: revision + "\n") }
    }

    func testExplicitPrecisionBoundaryAndFiniteAffineMapping() throws {
        // Exact binary arithmetic witnesses; this is not an owning product precision profile.
        let precision = try PDFGeometryPrecision(maximumErrorPDFPoints: 0.5)
        try precision.validate(expected: PDFPoint(x: 0, y: 0), actual: PDFPoint(x: 0.5, y: -0.5))
        assertError(.roundtripExceeded) {
            try precision.validate(expected: PDFPoint(x: 0, y: 0),
                                   actual: PDFPoint(x: Double(0.5).nextUp, y: 0))
        }
        let exact = try PDFGeometryPrecision(maximumErrorPDFPoints: 0)
        let affine = try PDFGeometryAffine(a: 0, b: 2, c: -2, d: 0, tx: 400, ty: -20)
        let point = PDFPoint(x: 35, y: 80)
        XCTAssertEqual(try affine.applying(point), PDFPoint(x: 240, y: 50))
        try exact.validate(expected: point, actual: affine.inverse(PDFPoint(x: 240, y: 50)))
        assertError(.malformedGeometry) {
            try PDFGeometryAffine(a: 1, b: 2, c: 2, d: 4, tx: 0, ty: 0)
        }
        assertError(.malformedGeometry) {
            try affine.applying(PDFPoint(x: .nan, y: 0))
        }
        assertError(.malformedGeometry) {
            try PDFGeometryAffine(a: .infinity, b: 0, c: 0, d: 1, tx: 0, ty: 0)
        }
    }

    @MainActor
    func testPDFKitSyntheticPageMappingAllRotationsAndDifferentPage() throws {
        // Source-only fixture: no user file, PDFium/helper, render, window or native-frame trial.
        let bytes = NSMutableData()
        let consumer = try XCTUnwrap(CGDataConsumer(data: bytes as CFMutableData))
        var mediaBox = CGRect(x: 0, y: 0, width: 300, height: 400)
        let context = try XCTUnwrap(CGContext(consumer: consumer, mediaBox: &mediaBox, nil))
        context.beginPDFPage(nil)
        context.endPDFPage()
        context.closePDF()
        let document = try XCTUnwrap(PDFDocument(data: bytes as Data))
        let pdfPage = try XCTUnwrap(document.page(at: 0))
        pdfPage.setBounds(CGRect(x: 10, y: 20, width: 100, height: 200), for: .cropBox)
        let view = PDFView(frame: CGRect(x: 0, y: 0, width: 600, height: 800))
        view.displayMode = .singlePage
        view.autoScales = false
        view.document = document
        let exact = try PDFGeometryPrecision(maximumErrorPDFPoints: 0)
        for rotation in [0, 90, 180, 270] {
            pdfPage.rotation = rotation
            for scale in [1.0, 2.0] {
                view.scaleFactor = scale
                view.layoutDocumentView()
                let geometry = try PDFKitGeometryAdapter.pageGeometry(page: pdfPage, in: view, pageIndex: 0)
                XCTAssertEqual(geometry, try page(rotation: rotation))
                let canonical = PDFPoint(x: 35, y: 80)
                let landmarks = [geometry.cropOrigin,
                                 PDFPoint(x: 110, y: 20), PDFPoint(x: 10, y: 220),
                                 PDFPoint(x: 110, y: 220), canonical]
                let publicDisplay = landmarks.map {
                    view.convert(CGPoint(x: $0.x, y: $0.y), from: pdfPage)
                }
                let publicBack = publicDisplay.map { view.convert($0, to: pdfPage) }
                // Fixture-only IEEE-754 forward-error budget, not a product profile.
                // u is binary64 unit roundoff. gamma(64) = 64u/(1-64u) covers
                // a conservative 64 scalar operations along the affine path:
                // basis differences/divisions, intercept construction, application,
                // determinant/inversion and forward/inverse affine evaluation.
                // Sum absolute page/display terms (display divided by this fixture's
                // uniform scale) rather than net coordinates: translations can cancel.
                // PDFKit's implementation is opaque; independently ASSERT its public
                // roundtrip fits this model. Never derive the budget from residuals.
                let u = Double.ulpOfOne / 2
                let gamma64 = (64 * u / (1 - 64 * u)).nextUp
                let magnitude = landmarks.reduce(0.0) { $0 + abs($1.x) + abs($1.y) }
                    + publicDisplay.reduce(0.0) {
                        $0 + (abs(Double($1.x)) + abs(Double($1.y))) / scale
                    } + geometry.width + geometry.height
                let bound = (gamma64 * magnitude).nextUp
                XCTAssertTrue(bound.isFinite && bound > 0)
                let configured = try PDFGeometryPrecision(maximumErrorPDFPoints: bound)
                for (landmark, back) in zip(landmarks, publicBack) {
                    let actual = PDFPoint(x: Double(back.x), y: Double(back.y))
                    try configured.validate(expected: landmark, actual: actual)
                    if actual != landmark {
                        // Zero really means zero: independent public PDFKit rounding
                        // must fail, not get silently accepted by the adapter.
                        assertError(.roundtripExceeded) {
                            try exact.validate(expected: landmark, actual: actual)
                        }
                        assertError(.roundtripExceeded) {
                            try PDFKitGeometryAdapter.displayPoint(
                                landmark, page: pdfPage, in: view,
                                geometry: geometry, precision: exact)
                        }
                    }
                }
                let display = try PDFKitGeometryAdapter.displayPoint(canonical, page: pdfPage, in: view,
                                                                    geometry: geometry, precision: configured)
                let direct = view.convert(CGPoint(x: 35, y: 80), from: pdfPage)
                XCTAssertEqual(display.x, Double(direct.x), accuracy: bound * scale)
                XCTAssertEqual(display.y, Double(direct.y), accuracy: bound * scale)
                let restored = try PDFKitGeometryAdapter.canonicalPoint(
                    display, page: pdfPage, in: view, geometry: geometry, precision: configured)
                try configured.validate(expected: canonical, actual: restored)
                assertError(.outsidePage) {
                    try PDFKitGeometryAdapter.displayPoint(PDFPoint(x: 9, y: 80), page: pdfPage, in: view,
                                                            geometry: geometry, precision: exact)
                }
            }
        }
        assertError(.missingPage) {
            try PDFKitGeometryAdapter.pageGeometry(page: pdfPage, in: PDFView(), pageIndex: 0)
        }
        assertError(.missingPage) {
            try PDFKitGeometryAdapter.pageGeometry(page: pdfPage, in: view, pageIndex: 1)
        }
        let otherDocument = try XCTUnwrap(PDFDocument(data: bytes as Data))
        let otherPage = try XCTUnwrap(otherDocument.page(at: 0))
        assertError(.differentPage) {
            try PDFKitGeometryAdapter.pageGeometry(page: otherPage, in: view, pageIndex: 0)
        }
    }
}
