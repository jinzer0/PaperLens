    func testCropBoxMapAvoidsAbsoluteInterceptCancellationWithoutClamping() throws {
        let geometry = try PDFPageGeometry(pageIndex: 0, cropOrigin: .init(x: 17.25, y: -23.5),
                                            width: 200, height: 300, rotation: 0)
        let origin = PDFPoint(x: 317.25, y: 4000.125)
        let right = PDFPoint(x: 337.25, y: 4000.125)
        let top = PDFPoint(x: 317.25, y: 4030.125)
        let stable = try PDFKitCropBoxTransform(geometry: geometry,
            displayBounds: CGRect(x: origin.x, y: origin.y, width: 20, height: 30), flipped: false)
        let boundary = PDFPoint(x: 217.25, y: -23.5)
        // Reproduce the former absolute-intercept evaluation on these exact inputs.
        let absolute = try PDFGeometryAffine(a: 0.1, b: 0, c: 0, d: 0.1,
                                              tx: origin.x - 0.1 * 17.25,
                                              ty: origin.y - 0.1 * -23.5)
        let cancelled = try absolute.inverse(right)
        assertError(.outsidePage) { try geometry.validate(cancelled) }
        XCTAssertEqual(try stable.applying(boundary), right)
        XCTAssertEqual(try stable.inverse(right), boundary)
        XCTAssertEqual(try stable.inverse(origin), geometry.cropOrigin)
        XCTAssertEqual(try stable.inverse(top), PDFPoint(x: 17.25, y: 276.5))
        // A distinct representable display point beyond the edge is NOT snapped back.
        assertError(.outsidePage) { try stable.inverse(.init(x: right.x.nextUp, y: right.y)) }
    }

    func testCropBoxMapExactEndpointsRotationsFlipsAndStrictViewContainment() throws {
        // Fixed correspondence table, not generated by the adapter's rotation algebra.
        let corners: [[PDFPoint]] = [
            [.init(x: 0, y: 0), .init(x: 1, y: 0), .init(x: 0, y: 1), .init(x: 1, y: 1)],
            [.init(x: 0, y: 1), .init(x: 0, y: 0), .init(x: 1, y: 1), .init(x: 1, y: 0)],
            [.init(x: 1, y: 1), .init(x: 0, y: 1), .init(x: 1, y: 0), .init(x: 0, y: 0)],
            [.init(x: 1, y: 0), .init(x: 1, y: 1), .init(x: 0, y: 0), .init(x: 0, y: 1)]
        ]
        let interiorFractions = [PDFPoint(x: 0.25, y: 0.25), .init(x: 0.25, y: 0.75),
                                 .init(x: 0.75, y: 0.75), .init(x: 0.75, y: 0.25)]
        for turn in 0..<4 {
            let geometry = try PDFPageGeometry(pageIndex: 0, cropOrigin: .init(x: 16, y: -32),
                                                width: 128, height: 256, rotation: turn * 90)
            let rect = CGRect(x: 4096, y: -8192, width: turn % 2 == 0 ? 64 : 128,
                              height: turn % 2 == 0 ? 128 : 64)
            let canonical = [PDFPoint(x: 16, y: -32), .init(x: 144, y: -32),
                             .init(x: 16, y: 224), .init(x: 144, y: 224), .init(x: 48, y: 32)]
            for flipped in [false, true] {
                let mapping = try PDFKitCropBoxTransform(geometry: geometry, displayBounds: rect, flipped: flipped)
                for (point, fraction) in zip(canonical, corners[turn] + [interiorFractions[turn]]) {
                    let expected = PDFPoint(x: rect.minX + fraction.x * rect.width,
                        y: rect.minY + (flipped ? 1 - fraction.y : fraction.y) * rect.height)
                    XCTAssertEqual(try mapping.applying(point), expected)
                    XCTAssertEqual(try mapping.inverse(expected), point)
                }
                for outside in [PDFPoint(x: rect.minX.nextDown, y: rect.midY),
                    .init(x: rect.maxX.nextUp, y: rect.midY),
                    .init(x: rect.midX, y: rect.minY.nextDown),
                    .init(x: rect.midX, y: rect.maxY.nextUp)] {
                    assertError(.outsidePage) { try mapping.inverse(outside) }
                }
            }
        }
    }

